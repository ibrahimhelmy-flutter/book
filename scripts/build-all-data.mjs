function safeWriteFileSync(filePath, content) {
  let attempts = 0;
  while (attempts < 5) {
    try {
      fs.writeFileSync(filePath, content, 'utf-8');
      return;
    } catch (e) {
      attempts++;
      if (attempts >= 5) throw e;
      const end = Date.now() + 60;
      while (Date.now() < end) { }
    }
  }
}

