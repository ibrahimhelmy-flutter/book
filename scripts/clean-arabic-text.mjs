// Robust Arabic Typography and OCR Normalizer for Canonical Data
export function cleanArabicTypography(text) {
  if (!text || typeof text !== 'string') return text;

  let cleaned = text;

  // 1. Broken Lam-Alif ligatures with prefixes (avoiding ASCII \b limitation)
  const prefixRules = [
    // Three-letter prefixes
    [/(^|[^\u0600-\u06FF])واأل/g, (m, p) => p + 'والأ'],
    [/(^|[^\u0600-\u06FF])واإل/g, (m, p) => p + 'والإ'],
    [/(^|[^\u0600-\u06FF])واآل/g, (m, p) => p + 'والآ'],
    [/(^|[^\u0600-\u06FF])واأ/g, (m, p) => p + 'والأ'],
    [/(^|[^\u0600-\u06FF])واإ/g, (m, p) => p + 'والإ'],
    [/(^|[^\u0600-\u06FF])واآ/g, (m, p) => p + 'والآ'],

    [/(^|[^\u0600-\u06FF])باأل/g, (m, p) => p + 'بالأ'],
    [/(^|[^\u0600-\u06FF])باإل/g, (m, p) => p + 'بالإ'],
    [/(^|[^\u0600-\u06FF])باآل/g, (m, p) => p + 'بالآ'],
    [/(^|[^\u0600-\u06FF])باأ/g, (m, p) => p + 'بالأ'],
    [/(^|[^\u0600-\u06FF])باإ/g, (m, p) => p + 'بالإ'],
    [/(^|[^\u0600-\u06FF])باآ/g, (m, p) => p + 'بالآ'],

    [/(^|[^\u0600-\u06FF])كاأل/g, (m, p) => p + 'كالأ'],
    [/(^|[^\u0600-\u06FF])كاأ/g, (m, p) => p + 'كالأ'],

    [/(^|[^\u0600-\u06FF])فاأل/g, (m, p) => p + 'فالأ'],
    [/(^|[^\u0600-\u06FF])فاأ/g, (m, p) => p + 'فالأ'],

    // Two-letter prefixes (األ / اإل / اآل / اأ / اإ / اآ)
    [/(^|[^\u0600-\u06FF])األ/g, (m, p) => p + 'الأ'],
    [/(^|[^\u0600-\u06FF])اإل/g, (m, p) => p + 'الإ'],
    [/(^|[^\u0600-\u06FF])اآل/g, (m, p) => p + 'الآ'],
    [/(^|[^\u0600-\u06FF])اأ/g, (m, p) => p + 'الأ'],
    [/(^|[^\u0600-\u06FF])اإ/g, (m, p) => p + 'الإ'],
    [/(^|[^\u0600-\u06FF])اآ/g, (m, p) => p + 'الآ'],

    // Inverted Alif-Lam (اال -> ال)
    [/(^|[^\u0600-\u06FF])االتصال/g, (m, p) => p + 'الاتصال'],
    [/(^|[^\u0600-\u06FF])االستدالل/g, (m, p) => p + 'الاستدلال'],
    [/(^|[^\u0600-\u06FF])االختيار/g, (m, p) => p + 'الاختيار'],
    [/(^|[^\u0600-\u06FF])االستخدام/g, (m, p) => p + 'الاستخدام'],
    [/(^|[^\u0600-\u06FF])االفتراضية/g, (m, p) => p + 'الافتراضية'],
    [/(^|[^\u0600-\u06FF])االصطناعية/g, (m, p) => p + 'الاصطناعية'],
    [/(^|[^\u0600-\u06FF])االصطناعي/g, (m, p) => p + 'الاصطناعي'],
    [/(^|[^\u0600-\u06FF])االستجابة/g, (m, p) => p + 'الاستجابة']
  ];

  for (const [regex, repl] of prefixRules) {
    cleaned = cleaned.replace(regex, repl);
  }

  // 2. Specific frequent OCR ligature corruptions
  const exactReplacements = [
    // Broken words
    [/الفيروسمات/g, 'الفيروسات'],
    [/الهجامت/g, 'الهجمات'],
    [/والتحسينن/g, 'والتحسين'],
    [/التحسينن/g, 'التحسين'],
    [/تحسينن/g, 'تحسين'],
    [/منوذجياً/g, 'نموذجياً'],
    [/منوذجيا/g, 'نموذجياً'],
    [/منوذجية/g, 'نموذجية'],
    [/منوذجي/g, 'نموذجي'],
    [/منوذج/g, 'نموذج'],
    [/النامذج/g, 'النماذج'],
    [/مناذج/g, 'نماذج'],
    [/مينعها/g, 'يمنعها'],
    [/مينع/g, 'يمنع'],
    [/مينح/g, 'يمنح'],
    [/مي ثل/g, 'يمثل'],
    [/مييز/g, 'يميز'],
    [/وسالمتها/g, 'وسلامتها'],
    [/سالمتها/g, 'سلامتها'],
    [/سالمة/g, 'سلامة'],
    [/كالتايل/g, 'كالتالي'],
    [/التايل/g, 'التالي'],
    [/تايل/g, 'تالي'],
    [/أعىل/g, 'أعلى'],
    [/أوال/g, 'أولاً'],
    [/أوالً/g, 'أولاً'],
    [/الأساىس/g, 'الأساسي'],
    [/األساىس/g, 'الأساسي'],
    [/الرئيىس/g, 'الرئيسي'],
    [/التشفيري/g, 'التشفير'],
    [/والتشفيري/g, 'والتشفير'],
    [/لتشفيري/g, 'للتشفير'],
    [/التشفيرية/g, 'التشفيرية'],
    [/األحكماًم/g, 'الأحكام'],
    [/أحكماًمه/g, 'أحكامه'],
    [/أحكماًم/g, 'أحكام'],
    [/حكماًم/g, 'حكماً'],
    [/األمناط/g, 'الأنماط'],
    [/أمناط/g, 'أنماط'],
    [/األعامل/g, 'الأعمال'],
    [/أعامل/g, 'أعمال'],
    [/يحتماًجها/g, 'يحتاجها'],
    [/يحتماًج/g, 'يحتاج'],
    [/تغييريت/g, 'تغيرت'],
    [/تغييري/g, 'تغيير'],
    [/المتغييريات/g, 'المتغيرات'],
    [/متغييري/g, 'متغير'],
    [/متغيير/g, 'متغير'],
    [/وحصراًسة/g, 'وحراسة'],
    [/الربمجة/g, 'البرمجة'],
    [/البصريد/g, 'البريد'],
    [/واألكرث/g, 'والأكثر'],
    [/األكرث/g, 'الأكثر'],
    [/أكرث/g, 'أكثر'],
    [/أكثير/g, 'أكثر'],
    [/يربع/g, 'يبرع'],
    [/السهام/g, 'لإسهام'],
    [/ترسب المعلومات/g, 'تسرب المعلومات'],
    [/الترسب/g, 'التسرب'],
    [/ترسب/g, 'تسرب'],
    // Attached word separation
    [/بينمالتشفيري/g, 'بينما التشفير'],
    [/بينمالتشفير/g, 'بينما التشفير'],
    [/بينمالذكاء/g, 'بينما الذكاء'],
    [/بينمالأمان/g, 'بينما الأمان'],
    [/بينماألدلة/g, 'بينما الأدلة'],
    [/بينمالجوانب/g, 'بينما الجوانب'],
    [/بينمالتعلم/g, 'بينما التعلم'],
    // Trailing/misplaced adjectives
    [/التشفيري\b/g, 'التشفير'],
    [/التحليالت\b/g, 'التحليلات']
  ];

  for (const [pattern, repl] of exactReplacements) {
    cleaned = cleaned.replace(pattern, repl);
  }

  // 3. Spacing and detached punctuation cleanups
  cleaned = cleaned
    .replace(/[ ]+([\.\،\؟\:\;\!])/g, '$1') // Detached punctuation
    .replace(/\.{3,}/g, '...') // Normalize long dots sequences
    .replace(/[ \t]{2,}/g, ' '); // Collapse double spaces

  return cleaned.trim();
}
