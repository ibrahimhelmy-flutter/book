import { describe, it } from "node:test";
import assert from "node:assert/strict";
import fs from "node:fs";
import path from "node:path";
import type { ExamsIndex, NavChapter } from "../../src/types/catalog";
import type { OfficialLessonAssessments } from "../../src/types/assessments";
import type { EnrichedSimpleQuestion } from "../../src/lib/practice";
import {
  INITIAL_FILTERS,
  NO_LESSONS,
  FINAL_PRESET,
  REVIEW_PRESET,
  examsFilterReducer,
  practiceScope,
  officialScope,
  difficultyCountsFromIndex,
  difficultyCountsFromQuestions,
  officialStatsFromIndex,
  officialStatsFromQuestions,
  filterOfficialQuestions,
  officialExamPool,
  paginate,
  presetRecipe,
  unitReviewInfo,
  unitReviewCountInScope,
  practiceScopeSummary,
  officialScopeSummary,
} from "../../src/components/exams/exams-logic";

// Generated by scripts/data/build-data.ts (run it if public/data is missing).
const PART_DIR = path.resolve("public/data/secondary-2/programming-ai/term-1");
const readJson = <T>(rel: string): T => JSON.parse(fs.readFileSync(path.join(PART_DIR, rel), "utf8")) as T;

const index = readJson<ExamsIndex>("exams-index.json");
const manifest = readJson<{ chapters: NavChapter[] }>("manifest.json");
const chapters = manifest.chapters;
const scopeOf = (patch: Partial<typeof INITIAL_FILTERS>) => ({ ...INITIAL_FILTERS, ...patch });

describe("Exams page logic (index-driven scope, filters, presets)", () => {
  it("reducer: chapter toggles reset lessons and pages; lesson toggle leaves the 'none' state", () => {
    let s = examsFilterReducer({ ...INITIAL_FILTERS, practicePage: 3, lessonKeys: ["1-1"] }, { type: "toggleChapter", chapterId: "chapter-2" });
    assert.deepEqual(s.chapterIds, ["chapter-2"]);
    assert.deepEqual(s.lessonKeys, []);
    assert.equal(s.practicePage, 1);

    s = examsFilterReducer(s, { type: "clearLessons" });
    assert.deepEqual(s.lessonKeys, [NO_LESSONS]);
    s = examsFilterReducer(s, { type: "toggleLesson", lessonKey: "2-1" });
    assert.deepEqual(s.lessonKeys, ["2-1"]);

    s = examsFilterReducer(INITIAL_FILTERS, { type: "toggleUnitReview", fallbackChapterId: "chapter-1" });
    assert.equal(s.unitReviewOnly, true);
    assert.deepEqual(s.chapterIds, ["chapter-1"]);
    s = examsFilterReducer(s, { type: "allChapters" });
    assert.equal(s.unitReviewOnly, false);
    assert.deepEqual(s.chapterIds, []);
  });

  it("practiceScope selects exactly the lesson files to fetch", () => {
    assert.equal(practiceScope(index, scopeOf({})).length, index.practice.length);
    assert.deepEqual(practiceScope(index, scopeOf({ lessonKeys: [NO_LESSONS] })), []);

    const ch1 = practiceScope(index, scopeOf({ chapterIds: ["chapter-1"] })).map((e) => e.lessonKey);
    assert.ok(ch1.includes("1-1") && ch1.includes("1-review"));
    assert.ok(ch1.every((k) => k.startsWith("1-")));

    assert.deepEqual(practiceScope(index, scopeOf({ lessonKeys: ["1-1", "2-1"] })).map((e) => e.lessonKey), ["1-1", "2-1"]);
    const reviews = practiceScope(index, scopeOf({ unitReviewOnly: true }));
    assert.ok(reviews.length > 0 && reviews.every((e) => e.isUnitReview));
  });

  it("officialScope filters by chapter and lesson number", () => {
    assert.equal(officialScope(index, scopeOf({})).length, index.official.length);
    const one = officialScope(index, scopeOf({ lessonKeys: ["1-2"] }));
    assert.deepEqual(one.map((e) => e.lessonId), ["lesson-1-2"]);
    assert.ok(officialScope(index, scopeOf({ chapterIds: ["chapter-3"] })).every((e) => e.chapterId === "chapter-3"));
  });

  it("index counts match the generated per-lesson practice files", () => {
    const totals = difficultyCountsFromIndex(index.practice);
    assert.equal(totals.all, index.totals.practice);
    for (const entry of index.practice) {
      const qs = readJson<EnrichedSimpleQuestion[]>(`practice/${entry.lessonKey}.json`);
      const counts = difficultyCountsFromQuestions(qs);
      assert.equal(counts.all, entry.count, `count mismatch for ${entry.lessonKey}`);
      assert.deepEqual({ easy: counts.easy, medium: counts.medium, hard: counts.hard }, entry.difficulty);
    }
    const review = unitReviewInfo(index);
    assert.ok(review);
    assert.equal(unitReviewCountInScope(index, []), review.totalCount);
    assert.equal(unitReviewCountInScope(index, ["chapter-4"]), index.practice.filter((e) => e.isUnitReview && e.chapterId === "chapter-4").reduce((n, e) => n + e.count, 0));
  });

  it("official filters, stats and exam pool work on a fetched lesson file", () => {
    const entry = index.official[0];
    const lesson = readJson<OfficialLessonAssessments>(`assessments/${entry.lessonId}.json`);
    const all = filterOfficialQuestions(lesson.questions, { section: "all", type: "all", search: "" });
    assert.deepEqual(officialStatsFromQuestions(all), officialStatsFromIndex([entry], "all"));

    const mcqs = filterOfficialQuestions(lesson.questions, { section: "all", type: "mcq", search: "" });
    assert.equal(mcqs.length, entry.mcqCount);
    assert.equal(officialStatsFromIndex([entry], "mcq").total, entry.mcqCount);

    const pool = officialExamPool(all);
    assert.ok(pool.length > 0 && pool.length <= entry.mcqCount);
    assert.ok(pool.every((q) => q.options.length === 4 && q.options.includes(q.answer)));
  });

  it("paginate clamps the page and presets resolve their lesson files", () => {
    const p = paginate(Array.from({ length: 25 }, (_, i) => i), 9);
    assert.equal(p.page, 3);
    assert.equal(p.totalPages, 3);
    assert.deepEqual(p.items, [20, 21, 22, 23, 24]);

    assert.equal(presetRecipe(FINAL_PRESET, index, chapters)?.lessonKeys.length, index.practice.length);
    assert.ok(presetRecipe(REVIEW_PRESET, index, chapters)?.lessonKeys.every((k) => k.endsWith("-review")));
    assert.ok(presetRecipe("chapter-2", index, chapters)?.lessonKeys.every((k) => k.startsWith("2-")));
    assert.equal(presetRecipe("chapter-99", index, chapters), null);
  });

  it("scope summaries describe the selection", () => {
    const lessonCount = chapters.reduce((n, c) => n + c.lessons.length, 0);
    assert.ok(practiceScopeSummary(chapters, scopeOf({}), unitReviewInfo(index)).includes(`${lessonCount} درساً`));
    assert.ok(officialScopeSummary(chapters, scopeOf({ lessonKeys: ["1-1"], officialType: "mcq" })).startsWith("الدرس 1-1"));
    assert.equal(practiceScopeSummary(chapters, scopeOf({ lessonKeys: [NO_LESSONS] }), null), "لم يتم تحديد أي درس");
  });
});
